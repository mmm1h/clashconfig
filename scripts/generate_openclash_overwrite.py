#!/usr/bin/env python3
"""Generate a native OpenClash module and its IPv4 bypass feed from Mihomo YAML."""

import argparse
import copy
import ipaddress
import os
from pathlib import Path
import sys
import tempfile

import yaml


ROOT = Path(__file__).resolve().parents[1]
TOKEN = "__GENERATED_YAML__"
HEADER = "# Generated by scripts/generate_openclash_overwrite.py; do not edit.\n"


def render(source, template, extra):
    config = yaml.safe_load(source)
    if not isinstance(config, dict):
        raise ValueError("Mihomo configuration must be a mapping")
    dns, sniffer, tun = (config.get(key) for key in ("dns", "sniffer", "tun"))
    if not all(isinstance(value, dict) for value in (dns, sniffer, tun)):
        raise ValueError("DNS, sniffer and TUN mappings are required")
    if template.count(TOKEN) != 1 or "[YAML]\n" not in template:
        raise ValueError("Template requires one generated YAML token in [YAML]")
    for name, value in (("dns.respect-rules", dns.get("respect-rules")),
                        ("sniffer.enable", sniffer.get("enable"))):
        if not isinstance(value, bool):
            raise ValueError(f"{name} must be a boolean")

    # OpenClash treats #DIRECT resolvers as proxied and appends plaintext
    # bootstrap DNS. Shared YAML aliases can spread that change into policies.
    # Reapply source DNS fields individually, retaining only the plugin's
    # listener. Independent copies also keep the generated YAML free of aliases.
    dns_patch = {key + "!": copy.deepcopy(value) for key, value in dns.items()
                 if key != "listen"}
    optional_dns = {"fallback", "fallback-filter", "proxy-server-nameserver-policy",
                    "direct-nameserver", "direct-nameserver-follow-policy"}
    hijack = tun.get("dns-hijack", [])
    if not isinstance(hijack, list) or not all(isinstance(v, str) for v in hijack):
        raise ValueError("tun.dns-hijack must be a string list")
    patch = {"dns-": sorted(optional_dns - dns.keys())}
    patch.update({
        "dns": dns_patch,
        "sniffer!": sniffer,
        "tun": {
            "auto-route": False,
            "auto-redirect": False,
            "auto-detect-interface": False,
            "strict-route": False,
            "route-exclude-address-": None,
            "route-exclude-address-set-": None,
            "dns-hijack": list(dict.fromkeys(["127.0.0.1:53", *hijack])),
        },
    })
    yaml_text = yaml.safe_dump(patch, allow_unicode=True, sort_keys=False)
    # The module parser expands dollar signs in [YAML]. Reject them instead of
    # silently altering a future regex/domain containing an environment token.
    if "$" in yaml_text:
        raise ValueError("Generated YAML contains '$', which OpenClash expands")
    module = (HEADER + template.replace(TOKEN, yaml_text.rstrip())
              .replace("__RESPECT_RULES__", str(int(dns["respect-rules"])))
              .replace("__SNIFFER_ENABLE__", str(int(sniffer["enable"])))
              .rstrip() + "\n")

    fake = ipaddress.ip_network(dns.get("fake-ip-range", "198.18.0.0/15"), strict=False)
    if fake.version != 4:
        raise ValueError("An IPv4 Fake-IP range is required")
    exclusions = tun.get("route-exclude-address", [])
    if not isinstance(exclusions, list):
        raise ValueError("tun.route-exclude-address must be a list")
    extra_lines = [line.split("#", 1)[0].strip() for line in extra.splitlines()]
    networks = set()
    for entry in [*exclusions, *filter(None, extra_lines)]:
        if not isinstance(entry, str):
            raise ValueError("Bypass entries must be CIDR strings")
        network = ipaddress.ip_network(entry, strict=False)
        if network.version != 4:
            if entry in exclusions:
                continue  # This feed is only consumed by the IPv4 firewall set.
            raise ValueError("Extra bypass entries must use IPv4")
        if network.overlaps(fake):
            raise ValueError("A bypass range overlaps the Fake-IP range")
        networks.add(network)
    if not networks:
        raise ValueError("Empty IPv4 bypass feed")
    addresses = sorted(networks, key=lambda n: (int(n.network_address), n.prefixlen))
    bypass = HEADER + "".join(f"{network}\n" for network in addresses)
    return module, bypass


def generate(root=ROOT, check=False):
    root = Path(root)
    directory = root / "openclash"
    module, bypass = render(
        (root / "mihomo.yaml").read_text(),
        (directory / "overwrite.template.conf").read_text(),
        (directory / "bypass_extra_ipv4.list").read_text(),
    )
    outputs = {directory / "overwrite.conf": module,
               directory / "bypass_ipv4.list": bypass}
    changed = {p: text for p, text in outputs.items()
               if not p.exists() or p.read_bytes() != text.encode()}
    if check:
        if changed:
            raise ValueError("Generated files are stale: " + ", ".join(p.name for p in changed))
        return []
    # Finish all validation and prepare both files before replacing outputs.
    pending = {}
    originals = {path: path.read_bytes() if path.exists() else None for path in changed}
    replaced = []
    try:
        for path, text in changed.items():
            fd, name = tempfile.mkstemp(prefix=".openclash-", dir=directory)
            pending[path] = Path(name)
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
                stream.write(text)
            pending[path].chmod(0o644)
        for path, temporary in pending.items():
            os.replace(temporary, path)
            replaced.append(path)
    except OSError:
        for path in reversed(replaced):
            if originals[path] is None:
                path.unlink()
            else:
                path.write_bytes(originals[path])
        raise
    finally:
        for temporary in pending.values():
            temporary.unlink(missing_ok=True)
    return list(changed)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files are stale")
    args = parser.parse_args()
    try:
        changed = generate(check=args.check)
    except (OSError, ValueError, yaml.YAMLError) as error:
        print(f"OpenClash generation failed: {error}", file=sys.stderr)
        return 1
    print("OpenClash artifacts current." if not changed else
          "Generated: " + ", ".join(p.name for p in changed))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
